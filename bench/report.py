"""Render docs/BENCHMARKS.md from bench/results/*.json.

.venv/bin/python -m bench.report
"""

import json
from pathlib import Path

HERE = Path(__file__).parent
RESULTS = HERE / "results"
DOC = HERE.parent / "docs" / "BENCHMARKS.md"


def _load(pattern: str) -> list:
    return [json.loads(p.read_text()) for p in sorted(RESULTS.glob(pattern))]


def _err(e: str) -> str:
    """Short error for tables: drop "(see /path/to/log)" details."""
    return e.split(" (see ")[0][:80]


def _pct(x) -> str:
    return "—" if x is None else f"{x:.0%}"


def llm_section(rows: list[dict]) -> list[str]:
    out = [
        "## LLM (llama.cpp on GTX 1650 Mobile, 4 GB)",
        "",
        "| Model | ctx / KV | Load | VRAM loaded / peak | Prefill tok/s (512 / 2k / 4k) | Decode tok/s "
        "| Prefix cache: cold → warm ms (tokens re-processed) |",
        "|---|---|---|---|---|---|---|",
    ]
    for r in rows:
        if "error" in r and "speed" not in r:
            out.append(
                f"| {r['model']} | {r.get('ctx')} / {r.get('kv')} | | | {_err(r['error'])} | | |"
            )
            continue
        sp, ca = r.get("speed", {}), r.get("cache", {})
        pf = sp.get("prefill_tps", {})
        prefill = " / ".join(str(pf.get(k, pf.get(str(k), "—"))) for k in (512, 2048, 4096))
        cache = (
            f"{ca['cold_prompt_ms']} → {ca['warm_prompt_ms']} ({ca.get('warm_tokens_processed')})"
            if ca
            else "—"
        )
        out.append(
            f"| {r['model']} | {r['ctx']} / {r['kv']} | {r.get('load_s', '—')} s "
            f"| {r.get('vram_loaded_mib', '—')} / {r.get('vram_peak_mib', '—')} MiB "
            f"| {prefill} | {sp.get('decode_tps', '—')} | {cache} |"
        )
    out += [
        "",
        "### Tool-calling accuracy (60 labelled prompts, bench/data/tool_prompts.jsonl)",
        "",
        "| Model | Mode | Right tool | Right tool + args | Valid output | Median / p90 latency |",
        "|---|---|---|---|---|---|",
    ]
    for r in rows:
        for mode in ("tools", "json"):
            s = r.get(mode)
            if not s:
                continue
            label = "native tools" if mode == "tools" else "JSON schema"
            kv = "" if r.get("kv") == "f16" else f" (KV {r['kv']})"
            out.append(
                f"| {r['model']}{kv} | {label} | {_pct(s['tool_acc'])} | {_pct(s['args_acc'])} "
                f"| {_pct(s['valid'])} | {s['latency_ms_median']} / {s['latency_ms_p90']} ms |"
            )
    vis = [(r["model"], w, v) for r in rows for w, v in r.get("vision", {}).items()]
    if vis:
        out += [
            "",
            "### Screen reading with the vision projector (synthetic dialog)",
            "",
            "| Model | Projector / image tokens | Latency | Read correctly | VRAM peak |",
            "|---|---|---|---|---|",
        ]
        for m, where, v in vis:
            if "error" in v:
                out.append(f"| {m} | {where} | {_err(v['error'])} | | |")
            else:
                out.append(
                    f"| {m} | {where} | {v['latency_ms']} ms | {_pct(v['read_ok'])} "
                    f"| {v['vram_peak_mib']} MiB |"
                )
    return out


def stt_section(rows: list[dict]) -> list[str]:
    out = [
        "## Speech-to-text (your recordings, CPU unless noted)",
        "",
        "| Variant | WER | Exact sentences | Names/places/tech words | Median / p90 latency | RTF |",
        "|---|---|---|---|---|---|",
    ]
    for r in rows:
        if "error" in r:
            out.append(f"| {r['variant']} | {r['error']} | | | | |")
            continue
        out.append(
            f"| {r['variant']} | {r['wer']:.1%} | {_pct(r['sentence_exact'])} "
            f"| {_pct(r['entity_recall'])} | {r['latency_ms_median']} / {r['latency_ms_p90']} ms "
            f"| {r['rtf']} |"
        )
    return out


def tts_section(rows: list[dict]) -> list[str]:
    out = [
        "## Text-to-speech (CPU)",
        "",
        "| Engine | Voice | First sentence (ms) | RTF on a 12 s reply |",
        "|---|---|---|---|",
    ]
    for r in rows:
        if "error" in r:
            out.append(f"| {r['engine']} | {r['error']} | | |")
        else:
            out.append(f"| {r['engine']} | {r['voice']} | {r['short_ms']} | {r['long_rtf']} |")
    return out


def main():
    lines = [
        "# TARS Phase 0 benchmarks",
        "",
        "Machine: HP Victus 16 · i5-11400H · 16 GB · GTX 1650 Mobile 4 GB (desktop on iGPU).",
        "Generated by `bench/report.py` from `bench/results/`.",
        "",
        "> **Power matters.** The LLM tables were measured on AC power. On battery the GPU",
        "> drops to P5 (660 of 1785 MHz) and Brain decode falls from ~36 to ~5 tok/s (see the",
        "> resident tables).",
        "",
    ]
    llm = _load("llm-*.json")
    if llm:
        lines += llm_section(llm) + [""]
    if (RESULTS / "stt.json").exists():
        lines += stt_section(json.loads((RESULTS / "stt.json").read_text())) + [""]
    for f in sorted(RESULTS.glob("resident*.json")):
        rows = json.loads(f.read_text())
        power = "on battery (GPU at P5 / 660 MHz)" if "battery" in f.name else "on AC"
        lines += [
            f"## Brain + Scout resident together, {power}",
            "",
            "| Brain slots | VRAM | Brain decode alone | Brain decode with Scout busy (6/4/3 threads) "
            "| Vision read |",
            "|---|---|---|---|---|",
        ]
        for r in rows:
            together = " / ".join(
                str(r[f"together_scout_t{t}"]["brain"]["decode_tps"]) for t in (6, 4, 3)
            )
            lines.append(
                f"| {r['brain_slots']} | {r['vram_mib']} MiB | {r['brain_alone']['decode_tps']} tok/s "
                f"| {together} tok/s | {r['vision_with_scout_t4_s']} s |"
            )
        lines.append("")
    if (RESULTS / "tts.json").exists():
        lines += tts_section(json.loads((RESULTS / "tts.json").read_text())) + [""]
    DOC.write_text("\n".join(lines))
    print(f"wrote {DOC}")


if __name__ == "__main__":
    main()
